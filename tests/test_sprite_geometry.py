class TestRegenerationIsByteStable(unittest.TestCase):
    """SC-9's determinism half, MEASURED WITHOUT GIT — so it holds in a shallow
    checkout with no history, and cannot be satisfied by an exit code that is
    zero either way. The whole roster, not one sheet: a clock, a global or an
    unseeded random.* in any of the 30 call sites lands here."""

    def test_two_consecutive_generations_produce_identical_bytes(self):
        before = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                  for p in _room_pngs()}
        self.assertEqual(
            len(before), ROOM_PNG_COUNT,
            f"hashed {len(before)} PNG(s); ROOM_PNG_COUNT is {ROOM_PNG_COUNT} "
            "— a glob that matched nothing must not pass this by comparing two "
            "empty dictionaries")
        proc = _run_generator()
        self.assertEqual(proc.returncode, 0, proc.stderr)
        _ROOM_DECODE_CACHE.clear()
        after = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in _room_pngs()}
        drifted = sorted(n for n in before
                         if n not in after or before[n] != after[n])
        self.assertEqual(
            drifted, [],
            "these sprites came out different on a second generation — the "
            "generator is not deterministic (SPRITES.md 7.4: every random goes "
            "through random.Random(<fixed literal seed>), one unique seed per "
            "call site): " + ", ".join(drifted))


