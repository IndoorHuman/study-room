def _room_pngs():
    """Every PNG in assets/room/, sorted for determinism."""
    return sorted(ROOM.glob("*.png"))


def _rgb_counts_from_rows(width, height, rows):
    """Opaque RGB triple -> PNG pixel count. A fully transparent pixel carries
    no colour, so alpha 0 is skipped: an RGBA (0,0,0,0) pixel is not black."""
    counts = {}
    for y in range(height):
        row = rows[y]
        for i in range(width):
            if row[i * 4 + 3] > 0:
                key = (row[i * 4], row[i * 4 + 1], row[i * 4 + 2])
                counts[key] = counts.get(key, 0) + 1
    return counts


def _strays_in_rows(width, height, rows, allowed=None):
    """THE INVERTED PREDICATE, isolated so it can be driven red IN MEMORY with
    no tree change at all: seen - allowed, not forbidden & seen. Returns the
    offending triples mapped to their pixel counts, because a failure message
    that names the colour but not how much of it there is cannot be triaged."""
    allowed = ALLOWED_RGB if allowed is None else allowed
    return {rgb: n
            for rgb, n in _rgb_counts_from_rows(width, height, rows).items()
            if rgb not in allowed}


_ROOM_DECODE_CACHE = {}


def _room_rgb_counts(path):
    """Decode once per file per process — the whole directory is ~0.9s."""
    key = str(path)
    if key not in _ROOM_DECODE_CACHE:
        width, height, rows = _png_rgba_rows(path)
        _ROOM_DECODE_CACHE[key] = _rgb_counts_from_rows(width, height, rows)
    return _ROOM_DECODE_CACHE[key]


